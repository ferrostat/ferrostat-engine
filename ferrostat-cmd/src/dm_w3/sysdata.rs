//! Example datasets for `sysuse`. They are synthetic: generated here from a
//! fixed-seed pseudo-random sequence, so they are identical on every
//! platform and carry no third-party content.

use std::collections::BTreeMap;

use ferrostat_core::{DataSet, Value, ValueLabel, VarType, Variable};

/// (name, description)
pub const NAMES: &[(&str, &str)] = &[
    ("households", "Synthetic household survey, 500 households"),
    ("salesmonthly", "Synthetic monthly sales series, 2010m1-2019m12"),
    ("trial", "Synthetic clinical trial with censored survival times"),
    ("wagepanel", "Synthetic wage panel, 200 persons x 6 years"),
];

/// Deterministic generator (SplitMix64) with uniform and normal draws.
struct Gen(u64);

impl Gen {
    fn next(&mut self) -> u64 {
        self.0 = self.0.wrapping_add(0x9E37_79B9_7F4A_7C15);
        let mut z = self.0;
        z = (z ^ (z >> 30)).wrapping_mul(0xBF58_476D_1CE4_E5B9);
        z = (z ^ (z >> 27)).wrapping_mul(0x94D0_49BB_1331_11EB);
        z ^ (z >> 31)
    }
    fn unif(&mut self) -> f64 {
        ((self.next() >> 11) as f64 + 0.5) / (1u64 << 53) as f64
    }
    fn normal(&mut self) -> f64 {
        let (u, v) = (self.unif(), self.unif());
        (-2.0 * u.ln()).sqrt() * (2.0 * std::f64::consts::PI * v).cos()
    }
}

fn round(x: f64, d: i32) -> f64 {
    let p = 10f64.powi(d);
    (x * p).round() / p
}

fn var(name: &str, ty: VarType, label: &str, fmt: &str, vals: &[f64]) -> Variable {
    let mut v = Variable::new(name, ty);
    v.label = label.into();
    v.format = fmt.into();
    for &x in vals {
        v.push(match ty {
            VarType::Byte => Value::Byte(x as i8),
            VarType::Int => Value::Int(x as i16),
            VarType::Long => Value::Long(x as i32),
            VarType::Float => Value::Float(x as f32),
            _ => Value::Double(x),
        });
    }
    v
}

fn labels(ds: &mut DataSet, name: &str, pairs: &[(f64, &str)]) {
    let mut l = ValueLabel::new(name);
    for (k, t) in pairs {
        l.add(*k, *t);
    }
    ds.value_labels.insert(name.into(), l);
}

fn finish(mut ds: DataSet, label: &str, vars: Vec<Variable>) -> DataSet {
    ds.n_obs = vars.first().map_or(0, |v| v.len());
    for v in vars {
        ds.add_variable(v).expect("unique names");
    }
    ds.datalabel = label.into();
    let mut c = BTreeMap::new();
    c.insert("note0".to_string(), "1".to_string());
    c.insert("note1".to_string(), "Synthetic data generated by Ferrostat for examples and tests.".to_string());
    ds.characteristics.insert("_dta".into(), c);
    ds
}

pub fn build(name: &str) -> Option<DataSet> {
    match name {
        "wagepanel" => Some(wagepanel()),
        "households" => Some(households()),
        "salesmonthly" => Some(salesmonthly()),
        "trial" => Some(trial()),
        _ => None,
    }
}

fn wagepanel() -> DataSet {
    let mut g = Gen(20_240_601);
    let mut ds = DataSet::new();
    let (mut id, mut year, mut female, mut educ, mut exper, mut union, mut lwage) = (vec![], vec![], vec![], vec![], vec![], vec![], vec![]);
    for i in 1..=200 {
        let f = if g.unif() < 0.5 { 1.0 } else { 0.0 };
        let e = (12.0 + 2.5 * g.normal()).round().clamp(8.0, 20.0);
        let x0 = (g.unif() * 20.0).floor();
        let ui = 0.25 * g.normal();
        let mut un = if g.unif() < 0.25 { 1.0 } else { 0.0 };
        for t in 0..6 {
            if g.unif() < 0.1 {
                un = 1.0 - un;
            }
            let x = x0 + t as f64;
            id.push(i as f64);
            year.push(2015.0 + t as f64);
            female.push(f);
            educ.push(e);
            exper.push(x);
            union.push(un);
            lwage.push(round(1.2 + 0.08 * e + 0.03 * x - 0.0005 * x * x - 0.15 * f + 0.1 * un + ui + 0.2 * g.normal(), 4));
        }
    }
    labels(&mut ds, "sexlbl", &[(0.0, "male"), (1.0, "female")]);
    labels(&mut ds, "yesno", &[(0.0, "no"), (1.0, "yes")]);
    let mut vf = var("female", VarType::Byte, "Female", "%8.0g", &female);
    vf.value_label_name = "sexlbl".into();
    let mut vu = var("union", VarType::Byte, "Union member", "%8.0g", &union);
    vu.value_label_name = "yesno".into();
    finish(
        ds,
        "Synthetic wage panel",
        vec![
            var("id", VarType::Int, "Person identifier", "%8.0g", &id),
            var("year", VarType::Int, "Year", "%8.0g", &year),
            vf,
            var("educ", VarType::Byte, "Years of schooling", "%8.0g", &educ),
            var("exper", VarType::Byte, "Years of experience", "%8.0g", &exper),
            vu,
            var("lwage", VarType::Float, "Log hourly wage", "%9.4f", &lwage),
        ],
    )
}

fn households() -> DataSet {
    let mut g = Gen(77_123);
    let mut ds = DataSet::new();
    let n = 500;
    let (mut hh, mut region, mut size, mut income, mut owner, mut urban) = (vec![], vec![], vec![], vec![], vec![], vec![]);
    for i in 1..=n {
        let r = (g.unif() * 4.0).floor() + 1.0;
        let u = if g.unif() < 0.6 { 1.0 } else { 0.0 };
        let s = (1.0 + (-2.6 * g.unif().ln()).floor()).min(9.0);
        let inc = (10.3 + 0.15 * u + 0.08 * s - 0.05 * (r - 1.0) + 0.6 * g.normal()).exp();
        let p_own = 1.0 / (1.0 + (-(-4.0 + 0.0001 * inc.min(80_000.0) - 0.5 * u)).exp());
        hh.push(i as f64);
        region.push(r);
        size.push(s);
        income.push(round(inc, 0));
        owner.push(if g.unif() < p_own { 1.0 } else { 0.0 });
        urban.push(u);
    }
    labels(&mut ds, "regionlbl", &[(1.0, "North"), (2.0, "South"), (3.0, "East"), (4.0, "West")]);
    let mut vr = var("region", VarType::Byte, "Region", "%8.0g", &region);
    vr.value_label_name = "regionlbl".into();
    finish(
        ds,
        "Synthetic household survey",
        vec![
            var("hhid", VarType::Int, "Household identifier", "%8.0g", &hh),
            vr,
            var("size", VarType::Byte, "Household size", "%8.0g", &size),
            var("income", VarType::Long, "Annual income", "%10.0fc", &income),
            var("owner", VarType::Byte, "Owns dwelling", "%8.0g", &owner),
            var("urban", VarType::Byte, "Urban area", "%8.0g", &urban),
        ],
    )
}

fn salesmonthly() -> DataSet {
    let mut g = Gen(4_242);
    let ds = DataSet::new();
    let (mut month, mut sales, mut price, mut promo) = (vec![], vec![], vec![], vec![]);
    let mut e = 0.0;
    for t in 0..120 {
        let m = 600 + t; // 2010m1
        e = 0.6 * e + 3.0 * g.normal();
        let pr = round(10.0 + 0.02 * t as f64 + 0.3 * g.normal(), 2);
        let pm = if g.unif() < 0.2 { 1.0 } else { 0.0 };
        let season = 8.0 * (2.0 * std::f64::consts::PI * (t % 12) as f64 / 12.0).sin();
        month.push(m as f64);
        price.push(pr);
        promo.push(pm);
        sales.push(round(100.0 + 0.5 * t as f64 + season - 2.0 * (pr - 10.0) + 6.0 * pm + e, 2));
    }
    finish(
        ds,
        "Synthetic monthly sales",
        vec![
            var("month", VarType::Int, "Month", "%tm", &month),
            var("sales", VarType::Float, "Units sold (thousands)", "%9.2f", &sales),
            var("price", VarType::Float, "Average price", "%9.2f", &price),
            var("promo", VarType::Byte, "Promotion running", "%8.0g", &promo),
        ],
    )
}

fn trial() -> DataSet {
    let mut g = Gen(9_001);
    let mut ds = DataSet::new();
    let (mut id, mut treat, mut age, mut time, mut died) = (vec![], vec![], vec![], vec![], vec![]);
    for i in 1..=300 {
        let tr = if i % 2 == 0 { 1.0 } else { 0.0 };
        let a = (60.0 + 8.0 * g.normal()).round();
        let rate = 0.05 * (0.03 * (a - 60.0) - 0.5 * tr).exp();
        let t_event = -g.unif().ln() / rate;
        let t_cens = 12.0 + 24.0 * g.unif();
        id.push(i as f64);
        treat.push(tr);
        age.push(a);
        time.push(round(t_event.min(t_cens), 2));
        died.push(if t_event <= t_cens { 1.0 } else { 0.0 });
    }
    labels(&mut ds, "treatlbl", &[(0.0, "placebo"), (1.0, "active")]);
    let mut vt = var("treat", VarType::Byte, "Treatment arm", "%8.0g", &treat);
    vt.value_label_name = "treatlbl".into();
    finish(
        ds,
        "Synthetic survival trial",
        vec![
            var("id", VarType::Int, "Patient identifier", "%8.0g", &id),
            vt,
            var("age", VarType::Byte, "Age at entry", "%8.0g", &age),
            var("time", VarType::Float, "Months of follow-up", "%9.2f", &time),
            var("died", VarType::Byte, "1 if died, 0 if censored", "%8.0g", &died),
        ],
    )
}
