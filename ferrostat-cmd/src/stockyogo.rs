/// Maximal relative biases tabulated in `TSLS_BIAS`.
pub const BIAS_LEVELS: [f64; 4] = [0.05, 0.10, 0.20, 0.30];
/// Maximal Wald test sizes tabulated in `TSLS_SIZE`.
pub const SIZE_LEVELS: [f64; 4] = [0.10, 0.15, 0.20, 0.25];

fn lookup<const W: usize>(table: &[(usize, [f64; W])], n: usize, k2: usize, groups: usize) -> Option<[f64; 4]> {
    if n == 0 || n > groups {
        return None;
    }
    let row = table.iter().find(|(k, _)| *k == k2)?.1;
    let v: [f64; 4] = std::array::from_fn(|i| row[(n - 1) * 4 + i]);
    if v.iter().all(|x| x.is_nan()) { None } else { Some(v) }
}

/// Critical values for maximal TSLS relative bias (5%, 10%, 20%, 30%).
pub fn tsls_bias(n: usize, k2: usize) -> Option<[f64; 4]> {
    lookup(&TSLS_BIAS, n, k2, 3)
}

/// Critical values for maximal TSLS Wald test size (10%, 15%, 20%, 25%).
pub fn tsls_size(n: usize, k2: usize) -> Option<[f64; 4]> {
    lookup(&TSLS_SIZE, n, k2, 2)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn known_entries() {
        // single endogenous regressor, one instrument: 10% maximal size = 16.38
        assert_eq!(tsls_size(1, 1).unwrap()[0], 16.38);
        assert_eq!(tsls_bias(1, 3).unwrap(), [13.91, 9.08, 6.46, 5.39]);
        assert_eq!(tsls_bias(2, 10).unwrap()[1], 10.58);
        assert_eq!(tsls_size(2, 30).unwrap()[3], 18.35);
        // not tabulated
        assert!(tsls_bias(1, 2).is_none());
        assert!(tsls_bias(2, 3).is_none());
        assert!(tsls_size(2, 1).is_none());
        assert!(tsls_size(3, 5).is_none());
        assert!(tsls_size(1, 31).is_none());
    }
}
