#[cfg(not(target_arch = "wasm32"))]
pub use native::{bridge as bridge_classes, javacall};

#[cfg(not(target_arch = "wasm32"))]
mod native {
    use super::*;
    use crate::macros::unquote;
    use crate::progtools::{opt_arg, split_opts};
    use ferrostat_core::vfs;
    use ferrostat_core::Value;
    use ferrostat_parser::parser::parse_line;

    fn esc(s: &str) -> String {
        s.replace('\\', "\\\\").replace('\t', "\\t").replace('\n', "\\n").replace('\r', "\\r")
    }

    fn unesc(s: &str) -> String {
        let mut out = String::new();
        let mut it = s.chars();
        while let Some(c) = it.next() {
            if c == '\\' {
                match it.next() {
                    Some('t') => out.push('\t'),
                    Some('n') => out.push('\n'),
                    Some('r') => out.push('\r'),
                    Some(d) => out.push(d),
                    None => out.push('\\'),
                }
            } else {
                out.push(c);
            }
        }
        out
    }

    /// A JDK tool: `$JAVA_HOME/bin/name` or `name` on the search path.
    fn tool(name: &str) -> String {
        if let Ok(h) = std::env::var("JAVA_HOME") {
            let exe = if cfg!(windows) { format!("{name}.exe") } else { name.to_string() };
            let p = std::path::Path::new(&h).join("bin").join(exe);
            if vfs::exists(&p.display().to_string()) {
                return p.display().to_string();
            }
        }
        name.to_string()
    }

    /// Compile the bridge once; returns its class directory (to compile
    /// Java code against the toolkit classes).
    pub fn bridge() -> Result<String, String> {
        let base = vfs::temp_path(&format!("ferrostat-java-bridge-{}", env!("CARGO_PKG_VERSION")));
        let classes = format!("{base}/classes");
        let marker = format!("{classes}/ok");
        if vfs::exists(&marker) {
            return Ok(classes);
        }
        let mut files = Vec::new();
        for (rel, text) in bridge_sources() {
            let p = format!("{base}/src/{rel}");
            if let Some(dir) = std::path::Path::new(&p).parent() {
                vfs::create_dir_all(&dir.display().to_string()).map_err(|e| rc_err(603, format!("javacall: {e}")))?;
            }
            vfs::write(&p, text.as_bytes()).map_err(|e| rc_err(603, format!("javacall: {e}")))?;
            files.push(p);
        }
        vfs::create_dir_all(&classes).map_err(|e| rc_err(603, format!("javacall: {e}")))?;
        let out = std::process::Command::new(tool("javac"))
            .args(["-nowarn", "-d", &classes])
            .args(&files)
            .output()
            .map_err(|_| rc_err(5100, "javacall: no Java compiler (javac) found; install a JDK or set JAVA_HOME"))?;
        if !out.status.success() {
            return Err(rc_err(5100, format!("javacall: compiling the Java bridge failed:\n{}", String::from_utf8_lossy(&out.stderr))));
        }
        vfs::write(&marker, b"ok").map_err(|e| rc_err(603, format!("javacall: {e}")))?;
        Ok(classes)
    }

    fn resolve_jar(me: &AdoInterpreter, j: &str) -> Option<String> {
        if vfs::exists(j) {
            let p = std::path::Path::new(j);
            return Some(if p.is_absolute() { j.to_string() } else { std::path::Path::new(&vfs::current_dir()).join(p).display().to_string() });
        }
        crate::progtools::find_on_path(me, j, None, true, false).into_iter().next()
    }

    static COUNTER: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);

    pub fn javacall(me: &mut AdoInterpreter, r: &str) -> Result<String, String> {
        let (body, opts) = split_opts(r);
        let words: Vec<&str> = body.split_whitespace().collect();
        if words.len() < 2 {
            return Err(rc_err(198, "javacall class method [varlist] [if] [in], jars(jarlist) [args(argument list)]"));
        }
        let (class, method) = (words[0].to_string(), words[1].to_string());
        let after_class = body.trim_start().split_once(char::is_whitespace).map(|x| x.1).unwrap_or("").trim_start();
        let tail = after_class.split_once(char::is_whitespace).map(|x| x.1).unwrap_or("").trim().to_string();
        let jars_opt = opt_arg(&opts, "jars", 4).ok_or_else(|| rc_err(198, "option jars() required"))?;
        let mut jars = Vec::new();
        for j in jars_opt.split([';', ' ']).map(unquote).filter(|j| !j.is_empty()) {
            jars.push(resolve_jar(me, &j).ok_or_else(|| rc_err(601, format!("file {j} not found")))?);
        }
        let args: Vec<String> = opt_arg(&opts, "args", 4).map(|a| crate::macros::words(&a).into_iter().map(|w| unquote(&w)).collect()).unwrap_or_default();

        // varlist and sample
        let cmd = parse_line(&format!("javacall {tail}")).map_err(|e| rc_err(198, e.message))?;
        let ds = &me.engine.dataset;
        let names: Vec<String> = if cmd.main.trim().is_empty() { Vec::new() } else { ferrostat_cmd::varlist::expand(ds, cmd.main.trim())? };
        let n = ds.n_obs;
        let ifmask = if cmd.if_expr.is_some() {
            let mut c2 = cmd.clone();
            c2.in_range = None;
            ferrostat_cmd::util::touse(ds, &me.engine.store, &c2)?
        } else {
            vec![true; n]
        };
        let (in1, in2) = if cmd.in_range.is_some() {
            let mut c2 = cmd.clone();
            c2.if_expr = None;
            c2.if_raw = None;
            let m = ferrostat_cmd::util::touse(ds, &me.engine.store, &c2)?;
            (m.iter().position(|&b| b).map(|i| i + 1).unwrap_or(1), m.iter().rposition(|&b| b).map(|i| i + 1).unwrap_or(0))
        } else {
            (1, n)
        };

        // request
        let mut req = String::new();
        let mut line = |fields: &[&str]| {
            req.push_str(&fields.iter().map(|f| esc(f)).collect::<Vec<_>>().join("\t"));
            req.push('\n');
        };
        line(&["class", &class]);
        line(&["method", &method]);
        for a in &args {
            line(&["arg", a]);
        }
        line(&["nobs", &n.to_string()]);
        line(&["in", &in1.to_string(), &in2.to_string()]);
        let touse: String = ifmask.iter().map(|&b| if b { '1' } else { '0' }).collect();
        line(&["touse", &touse]);
        let mut var_idx = Vec::new();
        for name in &names {
            let vi = ds.vars.iter().position(|v| &v.name == name).ok_or_else(|| rc_err(111, format!("variable {name} not found")))?;
            var_idx.push(vi);
            let v = &ds.vars[vi];
            let is_str = v.var_type.is_string();
            let mut f: Vec<String> = vec!["var".into(), name.clone(), if is_str { "S".into() } else { "N".into() }];
            for i in 0..n {
                f.push(if is_str { ferrostat_cmd::util::cell_text(ds, v, i, false) } else { format!("{:?}", v.data[i].num()) });
            }
            let refs: Vec<&str> = f.iter().map(String::as_str).collect();
            line(&refs);
        }
        let st = &me.engine.store;
        for (k, v) in &st.globals {
            line(&["g", k, v]);
        }
        if let Some(frame) = st.frames.last() {
            for (k, v) in frame {
                line(&["l", k, v]);
            }
        }
        for (k, v) in &st.scalars {
            line(&["s", k, &format!("{v:?}")]);
        }

        let classes = bridge()?;
        let k = COUNTER.fetch_add(1, std::sync::atomic::Ordering::Relaxed);
        let req_path = vfs::temp_path(&format!("ferrostat-javacall-{}-{k}.req", std::process::id()));
        let resp_path = format!("{req_path}.out");
        vfs::write(&req_path, req.as_bytes()).map_err(|e| rc_err(603, format!("javacall: {e}")))?;
        let sep = if cfg!(windows) { ";" } else { ":" };
        let mut cp = vec![classes];
        cp.extend(jars);
        let entry = format!("{}.FsState", compat_package());
        let run = std::process::Command::new(tool("java")).args(["-cp", &cp.join(sep), &entry, &req_path, &resp_path]).output();
        let _ = vfs::remove(&req_path);
        let run = run.map_err(|_| rc_err(5100, "javacall: no Java runtime (java) found; install a JDK or set JAVA_HOME"))?;
        let resp = vfs::read_to_string(&resp_path);
        let _ = vfs::remove(&resp_path);
        let resp = match resp {
            Ok(t) => t,
            Err(_) => return Err(rc_err(5100, format!("javacall: the Java process failed:\n{}", String::from_utf8_lossy(&run.stderr).trim_end()))),
        };

        // apply the response
        let mut out = String::new();
        let mut rc = 0;
        for l in resp.lines() {
            let f: Vec<String> = l.split('\t').map(unesc).collect();
            let get = |i: usize| f.get(i).map(String::as_str).unwrap_or("");
            match get(0) {
                "D" => out.push_str(get(1)),
                "E" => {
                    out.push_str("{err}");
                    out.push_str(get(1));
                    out.push_str("{txt}");
                }
                "n" | "t" => {
                    let (Ok(v), Ok(o)) = (get(1).parse::<usize>(), get(2).parse::<usize>()) else { continue };
                    let (Some(&vi), true) = (var_idx.get(v.wrapping_sub(1)), o >= 1 && o <= n) else { continue };
                    let var = &mut me.engine.dataset.vars[vi];
                    if f[0] == "n" {
                        let x = get(3).parse::<f64>().ok().filter(|x| x.is_finite()).unwrap_or(ferrostat_core::missing::SYSMISS);
                        var.data[o - 1] = ferrostat_cmd::data::store_num(var.var_type, x);
                    } else {
                        var.data[o - 1] = Value::Str(get(3).to_string());
                    }
                    me.engine.store.data_changed = true;
                }
                "G" => {
                    me.engine.store.globals.insert(get(1).to_string(), get(2).to_string());
                }
                "L" => me.engine.store.set_local(get(1), get(2).to_string()),
                "S" => {
                    let x = get(2).parse::<f64>().unwrap_or(ferrostat_core::missing::SYSMISS);
                    me.engine.store.scalars.insert(get(1).to_string(), x);
                }
                "rc" => rc = get(1).parse().unwrap_or(0),
                _ => {}
            }
        }
        let text = ferrostat_cmd::w11::smcl::to_text(&out);
        if rc != 0 {
            return Err(rc_err(rc, text));
        }
        Ok(text)
    }
}
