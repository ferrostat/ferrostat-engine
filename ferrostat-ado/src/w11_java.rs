/// Java sources of the bridge: (relative path, text).
pub fn bridge_sources() -> Vec<(String, String)> {
    let compat = compat_package();
    let cdir = compat.replace('.', "/");
    let mut out = Vec::new();
    for (name, src) in [("FsState", STATE_JAVA), ("Data", DATA_JAVA), ("SFIToolkit", TOOLKIT_JAVA), ("Macro", MACRO_JAVA), ("Scalar", SCALAR_JAVA), ("Missing", MISSING_JAVA)] {
        out.push((format!("{cdir}/{name}.java"), src.replace("__PKG__", &compat)));
    }
    // the neutral package re-exports the static methods through subclasses
    let ndir = NEUTRAL_PACKAGE.replace('.', "/");
    for name in ["Data", "SFIToolkit", "Macro", "Scalar", "Missing"] {
        out.push((format!("{ndir}/{name}.java"), format!("package {NEUTRAL_PACKAGE};\n\npublic class {name} extends {compat}.{name} {{ }}\n")));
    }
    out
}

